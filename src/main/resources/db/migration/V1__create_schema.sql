create table badges
(
    id         varchar(64) primary key,
    title      varchar(128) not null,
    image      varchar(255) not null,
    priority   integer      not null default 0,
    created_at timestamptz  not null default now()
);

create table users
(
    twitch_id         varchar(32) primary key,
    login             varchar(64),
    display_name      varchar(64),
    selected_badge_id varchar(64) references badges (id) on delete set null,
    hide_badges       boolean     not null default false,
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now()
);

create table user_badges
(
    id         bigint generated by default as identity primary key,
    twitch_id  varchar(32) not null references users (twitch_id) on delete cascade,
    badge_id   varchar(64) not null references badges (id) on delete cascade,
    source     varchar(16) not null check (source in ('DONATION', 'GRANT')),
    granted_by varchar(32),
    granted_at timestamptz not null default now(),
    unique (twitch_id, badge_id)
);

create index user_badges_badge_id_idx on user_badges (badge_id);

create table donations
(
    se_channel_id varchar(64) primary key,
    twitch_id     varchar(32)  not null,
    name          varchar(255) not null,
    created_at    timestamptz  not null default now()
);

create index donations_twitch_id_idx on donations (twitch_id);
