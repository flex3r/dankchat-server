package com.flxrs.dankchat.server.legacy

import com.flxrs.dankchat.server.badge.BadgeSnapshotService
import com.flxrs.dankchat.server.resetDatabase
import io.quarkus.test.junit.QuarkusTest
import io.restassured.RestAssured.given
import jakarta.inject.Inject
import org.hamcrest.Matchers.equalTo
import org.hamcrest.Matchers.hasItems
import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.io.File
import java.sql.DriverManager
import javax.sql.DataSource

@QuarkusTest
class LegacyExportTest {
    @Inject
    lateinit var dataSource: DataSource

    @Inject
    lateinit var snapshots: BadgeSnapshotService

    @TempDir
    lateinit var legacyDir: File

    @BeforeEach
    fun setup() {
        resetDatabase()
        DriverManager.getConnection("jdbc:h2:file:${legacyDir.resolve("db").absolutePath}").use { connection ->
            connection.createStatement().use {
                it.execute(
                    """
                    CREATE TABLE USERS(
                        ID INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
                        "seId" CHARACTER VARYING(50) NOT NULL UNIQUE,
                        "twitchId" CHARACTER VARYING(50) NOT NULL UNIQUE,
                        NAME CHARACTER VARYING(255) NOT NULL
                    );
                    INSERT INTO USERS("seId", "twitchId", NAME) VALUES ('se-a', '100', 'alice'), ('se-b', '200', 'bob'), ('se-c', ' ', 'blank');
                    """.trimIndent(),
                )
            }
        }
        legacyDir.resolve("contributors.txt").writeText("300\n300\n100\n")
        legacyDir.resolve("optouts.txt").writeText("200\n")
        legacyDir.resolve("danks.json").writeText(
            """
            [
              {"type": "DuckerZ", "url": "https://flxrs.com/dankchat/badges/ente.gif", "users": ["400"]},
              {"type": "DankChat Supporter", "url": "https://flxrs.com/dankchat/badges/dank.png", "users": ["500"]},
              {"type": "FeelsDankMan", "url": "https://flxrs.com/dankchat/badges/crayon.gif", "users": []}
            ]
            """.trimIndent(),
        )
    }

    @Test
    fun `legacy data maps onto badges and applies idempotently`() {
        val sql = toSql(readLegacyData(legacyDir))
        repeat(2) {
            dataSource.connection.use { connection -> connection.createStatement().use { it.execute(sql) } }
        }
        snapshots.rebuild()

        given()
            .get("/v1/badges")
            .then()
            .statusCode(200)
            .body(
                "users",
                equalTo(
                    mapOf(
                        "73697410" to "developer",
                        "100" to "contributor",
                        "300" to "contributor",
                        "400" to "duckerz",
                        "500" to "supporter",
                    ),
                ),
            ).body("badges.id", hasItems("duckerz", "feelsdankman"))
            .body("badges.find { it.id == 'duckerz' }.url", equalTo("https://api.dank.chat/badges/ente.gif"))
    }
}
